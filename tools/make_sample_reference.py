#!/usr/bin/env python3
"""Create the reference summary for an offline sample.

The sample normally contains only raw WAL + config.  This tool runs one
offline replay and writes ``summary.json`` next to the sample so that the
sample can still exercise the ``replay --verify`` comparison path.  The summary
is explicitly marked as an offline reference, not a live run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tickforge.replay.runner import ReplayRunner


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sample", required=True)
    args = parser.parse_args()
    sample = Path(args.sample)
    runner = ReplayRunner(
        sample,
        out_dir=sample / "replay",
        write_derived=True,
        compare_reference=False,
    )
    result = runner.run()
    scan = result["scan"]
    counts = result["pipeline"]["counts"]
    summary = {
        "run_id": sample.name,
        "mode": "offline_reference",
        "note": (
            "Generated by tools/make_sample_reference.py from the sample WAL; "
            "this is an offline replay reference, not a live exchange run."
        ),
        "counts": {
            "pipeline": {
                key: counts[key]
                for key in (
                    "ws_frames",
                    "snapshots",
                    "factor_snapshots",
                    "signals",
                    "fills",
                )
            }
        },
        "digests": result["digests"],
        "wal": {
            "records_total": scan["records"],
            "records_ws": scan["records_by_kind"].get("1", 0),
            "records_snapshot": scan["records_by_kind"].get("2", 0),
        },
        "clean_shutdown": True,
    }
    out = sample / "summary.json"
    out.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"sample": str(sample), "summary": str(out), "counts": counts}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
